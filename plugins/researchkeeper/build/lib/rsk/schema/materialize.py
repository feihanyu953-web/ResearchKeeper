"""Deterministic, fail-closed materialization of an empty paper workspace."""

from __future__ import annotations

from dataclasses import dataclass
import os
from pathlib import Path
import shutil
from typing import Callable
import uuid

import yaml

from .contract import (
    SchemaPaths,
    SchemaProposal,
    schema_fingerprint,
    validate_builtin_vector_gate,
    validate_proposal,
)


RECORD_FIELDS = (
    "record_id",
    "schema_version",
    "paper_id",
    "module",
    "category",
    "subject",
    "metric",
    "value",
    "unit",
    "condition",
    "source",
    "confidence",
    "note",
)
_PROTOCOL_FILES = {
    "INDEX.md",
    "SCHEMA.md",
    "REVIEWER.md",
    "REVIEWER_LOG.md",
}


class SchemaMaterializationError(RuntimeError):
    """Raised when a schema cannot be safely published."""


@dataclass(frozen=True)
class MaterializationResult:
    status: str
    workspace: Path
    schema_fingerprint: str | None
    reused: bool = False


def _yaml_text(payload: object) -> str:
    return yaml.safe_dump(
        payload,
        allow_unicode=True,
        sort_keys=False,
        default_flow_style=False,
    )


def _modules_payload(proposal: SchemaProposal) -> dict[str, object]:
    return {
        "template_id": proposal.template_id,
        "template_version": proposal.template_version,
        "schema_version": proposal.schema_version,
        "modules": [module.as_dict() for module in proposal.modules],
    }


def _gate_payload(proposal: SchemaProposal) -> dict[str, object]:
    return {
        "sync_audit": {
            "pass": {"coverage": 1.0, "truncation": 0},
            "warn": {"coverage": 0.95, "truncation": "< 5"},
            "fail": {"coverage": "< 0.95", "truncation": ">= 5"},
        },
        "retrieval_audit": {
            "pass": {"fidelity": ">= 0.85", "recall": ">= 0.65"},
            "warn": {"fidelity": "0.65-0.85", "recall": "0.45-0.65"},
            "fail": {"fidelity": "< 0.65", "recall": "< 0.45"},
        },
        "test_queries": [
            dict(query) for query in proposal.vector_gate_queries
        ],
        "chain_test_queries": [
            dict(query) for query in proposal.vector_gate_chain_queries
        ],
    }


def _record_table(title: str) -> str:
    header = "| " + " | ".join(RECORD_FIELDS) + " |"
    separator = "|" + "|".join("---" for _field in RECORD_FIELDS) + "|"
    return f"# {title}\n\n{header}\n{separator}\n"


def _index_text(proposal: SchemaProposal) -> str:
    rows = "\n".join(
        f"| `{module.name}` | `{module.role}` | `kb/{module.file}` |"
        for module in proposal.modules
    )
    return (
        "# Knowledge Base Index\n\n"
        "The active concrete modules are authoritative for routing.\n\n"
        "| Module | Semantic role | File |\n"
        "|---|---|---|\n"
        f"{rows}\n\n"
        "Every paper requires `kb/coverage/<paper_id>.md`. Coverage is audit "
        "metadata and is excluded from semantic embeddings.\n"
    )


def _schema_text(proposal: SchemaProposal) -> str:
    rows = "\n".join(
        f"| `{module.name}` | `{module.role}` | `{module.file}` | "
        f"{module.description} |"
        for module in proposal.modules
    )
    fields = " | ".join(f"`{field}`" for field in RECORD_FIELDS)
    return (
        "# Active Knowledge Schema\n\n"
        f"Record contract: {fields}.\n\n"
        "New record sources must identify the paper and include at least one "
        "Fig./Table/Section/Methods/SI location. Bibliographic records may "
        "instead cite PDF front matter, Zotero metadata, or DOI metadata. "
        "Legacy source strings remain readable with compatibility warnings.\n\n"
        "| Module | Role | File | Purpose |\n"
        "|---|---|---|---|\n"
        f"{rows}\n\n"
        "---\n\n"
        "## Literature Module: Three Record Types\n\n"
        "The literature module carries three record categories per paper:\n\n"
        "### 1. Paper Index (1 per paper)\n"
        "- `category`: 论文索引\n"
        "- `metric`: 核心贡献 — one-sentence summary of what the paper "
        "achieved, using what method, solving what problem, and under what "
        "scope/limitation.\n"
        "- `subject`: paper_id + journal abbreviation\n"
        "- `condition`: research direction or reaction system\n\n"
        "### 2. Bibliographic Metadata (1 per paper, auto-generated)\n"
        "- `category`: 文献信息\n"
        "- `metric`: bibliographic_metadata\n"
        "- `value`: `Journal; Year; DOI: xxx`\n"
        "- `note`: JSON with title, authors, corresponding_authors, journal, "
        "year, doi, first_author_affiliation, corresponding_affiliations, "
        "affiliation_source, verification\n"
        "- **Generated by `rsk/kb/bibliography.py` from Zotero metadata + "
        "Crossref API. Do NOT write manually.**\n\n"
        "### 3. Evaluation Records (4-6 per paper)\n"
        "After deep reading, extract the following evaluation `metric` types "
        "from the reading notes (READING.md sections 4, 6, 7, 8):\n\n"
        "| `metric` | Content | Source Section |\n"
        "|---|---|---|\n"
        "| `创新代价` | Trade-offs: computation cost / data needs / convergence "
        "difficulty / generalization loss / process complexity | Section 6 |\n"
        "| `作者承认局限` | Limitations self-stated by authors in "
        "Limitations/Discussion | Section 7a |\n"
        "| `审稿质疑` | Strongest reviewer challenge per 6-dimension checklist "
        "(one dimension per record) | Section 7b |\n"
        "| `异常归因` | Counter-intuitive result compressed to 1-2 sentences + "
        "theoretical verdict (challenge/extension/limitation) | Section 4 |\n"
        "| `理论贡献` | How the paper revises/extends/challenges domain "
        "understanding | Section 8 theory track |\n"
        "| `实践启示` | Actionable protocols / criteria / parameter guidelines "
        "| Section 8 practice track |\n\n"
        "**Attribution Hard Rule**: Every evaluation record's `note` field MUST "
        "start with `attribution:` followed by exactly one of:\n\n"
        "- `attribution:作者` — explicitly stated by the authors in the paper\n"
        "- `attribution:AI审稿视角` — analytical judgment based on the paper\n"
        "- `attribution:AI推测` — AI supplement, not stated in the paper\n\n"
        "Additional notes follow after a **fullwidth vertical bar** "
        "(U+FF5C `｜`, never ASCII `|` which breaks the Markdown table):\n"
        "`attribution:AI推测｜additional context here...`\n\n"
        "The reviewer (audit dimension: literature completeness) will flag "
        "evaluation records that lack an `attribution:` prefix.\n"
    )


def _reviewer_text(proposal: SchemaProposal) -> str:
    sections = []
    for module in proposal.modules:
        focus = ", ".join(module.audit_focus)
        sections.append(
            f"- `{module.name}` (`{module.role}`, `kb/{module.file}`): {focus}"
        )
    return (
        "# Active Independent Reviewer Policy\n\n"
        "Mandatory reads: `schemas/generated/modules.yaml`, `kb/INDEX.md`, "
        "`kb/SCHEMA.md`, this file, the paper coverage declaration, actual "
        "module records, and the original paper/SI.\n\n"
        "The reviewer is read-only. Verify provenance, required fields, "
        "duplicates, conflicts, numeric accuracy, and cross-module "
        "consistency. Independently verify every `not_applicable` reason and "
        "evidence location; unavailable source evidence cannot receive a "
        "verified PASS.\n\n"
        "## Module-specific focus\n\n"
        + "\n".join(sections)
        + "\n"
    )


def _config_text() -> str:
    return _yaml_text(
        {
            "schema": {
                "modules": "schemas/generated/modules.yaml",
                "vector_gate_queries": (
                    "schemas/generated/vector_gate_queries.yaml"
                ),
            },
            "kb_modules": "schemas/generated/modules.yaml",
            "vector_db_dir": "vector_db",
            "audit": {
                "vector_gate_config": (
                    "schemas/generated/vector_gate_queries.yaml"
                )
            },
            "compute_kb": {"enabled": False},
        }
    )


def _schema_paths(root: Path) -> SchemaPaths:
    return SchemaPaths(
        modules=root / "schemas" / "generated" / "modules.yaml",
        vector_gate_queries=(
            root / "schemas" / "generated" / "vector_gate_queries.yaml"
        ),
        index=root / "kb" / "INDEX.md",
        schema=root / "kb" / "SCHEMA.md",
        reviewer=root / "kb" / "REVIEWER.md",
    )


def _write_stage(stage: Path, proposal: SchemaProposal) -> None:
    generated = stage / "schemas" / "generated"
    kb = stage / "kb"
    generated.mkdir(parents=True)
    (kb / "coverage").mkdir(parents=True)

    (stage / "rsk_config.yaml").write_text(
        _config_text(),
        encoding="utf-8",
        newline="\n",
    )
    (generated / "modules.yaml").write_text(
        _yaml_text(_modules_payload(proposal)),
        encoding="utf-8",
        newline="\n",
    )
    (generated / "vector_gate_queries.yaml").write_text(
        _yaml_text(_gate_payload(proposal)),
        encoding="utf-8",
        newline="\n",
    )
    (kb / "INDEX.md").write_text(
        _index_text(proposal),
        encoding="utf-8",
        newline="\n",
    )
    (kb / "SCHEMA.md").write_text(
        _schema_text(proposal),
        encoding="utf-8",
        newline="\n",
    )
    (kb / "REVIEWER.md").write_text(
        _reviewer_text(proposal),
        encoding="utf-8",
        newline="\n",
    )
    (kb / "REVIEWER_LOG.md").write_text(
        "# Reviewer Log\n\nNo paper content has been audited.\n",
        encoding="utf-8",
        newline="\n",
    )
    # Vector-layer reviewer protocol: ship the bundled template so the
    # vector-retrieval-auditor finds its own REVIEWER.md in the workspace
    # instead of borrowing kb/REVIEWER.md.
    vector_db = stage / "vector_db"
    vector_db.mkdir(parents=True, exist_ok=True)
    _reviewer_template = (
        Path(__file__).resolve().parent.parent
        / "audit"
        / "vector_db_REVIEWER.md"
    )
    (vector_db / "REVIEWER.md").write_text(
        _reviewer_template.read_text(encoding="utf-8"),
        encoding="utf-8",
        newline="\n",
    )
    for module in proposal.modules:
        (kb / module.file).write_text(
            _record_table(module.display),
            encoding="utf-8",
            newline="\n",
        )


def _proposal_from_stage(root: Path) -> SchemaProposal:
    modules_payload = yaml.safe_load(
        _schema_paths(root).modules.read_text(encoding="utf-8")
    )
    gate_payload = yaml.safe_load(
        _schema_paths(root).vector_gate_queries.read_text(encoding="utf-8")
    )
    return SchemaProposal.from_mapping(
        {
            **modules_payload,
            "vector_gate_queries": gate_payload.get("test_queries", []),
            "vector_gate_chain_queries": gate_payload.get(
                "chain_test_queries",
                [],
            ),
        }
    )


def validate_materialized_schema(root: Path) -> list[str]:
    errors: list[str] = []
    paths = _schema_paths(root)
    required = (
        root / "rsk_config.yaml",
        paths.modules,
        paths.vector_gate_queries,
        paths.index,
        paths.schema,
        paths.reviewer,
        root / "kb" / "REVIEWER_LOG.md",
        root / "kb" / "coverage",
    )
    for path in required:
        if not path.exists():
            errors.append(f"missing materialized path: {path.relative_to(root)}")
    if errors:
        return errors
    try:
        proposal = _proposal_from_stage(root)
    except (OSError, ValueError, TypeError, yaml.YAMLError) as exc:
        return [f"cannot read materialized schema: {exc}"]
    errors.extend(validate_proposal(proposal))
    if proposal.vector_gate_chain_queries:
        errors.extend(validate_builtin_vector_gate(proposal))
    for module in proposal.modules:
        if not (root / "kb" / module.file).is_file():
            errors.append(f"missing module file: kb/{module.file}")
    return errors


def has_knowledge_records(workspace: Path) -> bool:
    kb = workspace / "kb"
    if not kb.is_dir():
        return False
    for path in kb.glob("*.md"):
        if path.name in _PROTOCOL_FILES:
            continue
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.lstrip().startswith("|"):
                continue
            cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
            if len(cells) != len(RECORD_FIELDS):
                continue
            first = cells[0]
            if first == "record_id" or set(first) <= {"-", ":"}:
                continue
            if first:
                return True
    return False


def workspace_schema_status(workspace: Path) -> str:
    """Return the stable schema state for one explicit workspace."""
    workspace = Path(workspace).expanduser().resolve()
    paths = _schema_paths(workspace)
    generated = workspace / "schemas" / "generated"
    if not generated.exists() and not paths.modules.exists():
        return "unconfigured"
    if validate_materialized_schema(workspace):
        return "invalid"
    return (
        "configured_nonempty"
        if has_knowledge_records(workspace)
        else "configured_empty"
    )


def active_schema_fingerprint(workspace: Path) -> str:
    """Return the fingerprint of a valid active workspace schema."""
    workspace = Path(workspace).expanduser().resolve()
    status = workspace_schema_status(workspace)
    if status not in {"configured_empty", "configured_nonempty"}:
        raise SchemaMaterializationError(
            f"workspace schema is {status}, not configured"
        )
    return schema_fingerprint(_schema_paths(workspace))


def _existing_schema_matches(
    workspace: Path,
    proposal: SchemaProposal,
) -> bool:
    paths = _schema_paths(workspace)
    if not paths.modules.is_file() or not paths.vector_gate_queries.is_file():
        return False
    return (
        paths.modules.read_text(encoding="utf-8")
        == _yaml_text(_modules_payload(proposal))
        and paths.vector_gate_queries.read_text(encoding="utf-8")
        == _yaml_text(_gate_payload(proposal))
    )


def materialize_schema(
    *,
    workspace: Path,
    template_root: Path,
    proposal: SchemaProposal,
    approved: bool = True,
    staging_validator: Callable[[Path], list[str]] | None = None,
) -> MaterializationResult:
    del template_root  # The caller resolves templates before materialization.
    workspace = Path(workspace).expanduser().resolve()
    if not approved:
        return MaterializationResult(
            status="cancelled",
            workspace=workspace,
            schema_fingerprint=None,
        )

    proposal_errors = validate_proposal(proposal)
    if proposal_errors:
        raise SchemaMaterializationError("; ".join(proposal_errors))

    if workspace.exists() and has_knowledge_records(workspace):
        raise SchemaMaterializationError(
            "schema changes are disabled after a knowledge record exists"
        )
    if workspace.exists() and _existing_schema_matches(workspace, proposal):
        errors = validate_materialized_schema(workspace)
        if errors:
            raise SchemaMaterializationError(
                "active schema is invalid: " + "; ".join(errors)
            )
        return MaterializationResult(
            status="configured_empty",
            workspace=workspace,
            schema_fingerprint=schema_fingerprint(_schema_paths(workspace)),
            reused=True,
        )
    if workspace.exists():
        _protected_paths: set[str] = {"kb", "schemas", "rsk_config.yaml"}
        _existing_protected = {
            entry.name
            for entry in workspace.iterdir()
            if entry.name in _protected_paths
        }
        if _existing_protected:
            raise SchemaMaterializationError(
                "conflicting schema: workspace already contains schema paths "
                + ", ".join(sorted(_existing_protected))
                + "; migration is unsupported"
            )

    stage = workspace.parent / (
        f"{workspace.name}.rsk-schema-staging-{uuid.uuid4().hex}"
    )
    validator = staging_validator or validate_materialized_schema
    promoted_into_existing: list[Path] = []
    try:
        _write_stage(stage, proposal)
        staging_errors = validator(stage)
        if staging_errors:
            raise SchemaMaterializationError(
                "staging validation failed: " + "; ".join(staging_errors)
            )
        if workspace.exists():
            # Merge staged entries into the existing workspace
            # instead of replacing the workspace.
            # This preserves unrelated files (.claude/, docs/, etc.).
            for source in stage.iterdir():
                destination = workspace / source.name
                os.replace(source, destination)
                promoted_into_existing.append(destination)
            stage.rmdir()
        else:
            os.replace(stage, workspace)
    except Exception:
        shutil.rmtree(stage, ignore_errors=True)
        for destination in reversed(promoted_into_existing):
            if destination.is_dir():
                shutil.rmtree(destination, ignore_errors=True)
            else:
                destination.unlink(missing_ok=True)
        raise

    return MaterializationResult(
        status="configured_empty",
        workspace=workspace,
        schema_fingerprint=schema_fingerprint(_schema_paths(workspace)),
    )
